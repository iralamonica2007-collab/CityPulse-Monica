#Comparison Operators

a = 10
b = 5

print("Equal:", a == b)
print("Not equal:", a != b)
print("Greater than:", a > b)
print("Less than:", a < b)
print("Greater than or equal:", a >= b)
print("Less than or equal:", a <= b)

#Logical Operators
age = 20
marks = 85

print("AND:", age > 18 and marks > 50)
print("OR:", age > 18 or marks < 50)
print("NOT:", not(age > 18))

